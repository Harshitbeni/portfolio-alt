const WORK_MEDIA_LAYOUT_OPTIONS = [
  { value: "stack", label: "Stacked" },
  { value: "row", label: "Horizontal centered" },
] as const;

function workMediaLayoutFromDial(value: string): Extract<
  WorkMediaLayout,
  "stack" | "row"
> {
  return value === "row" ? "row" : "stack";
}

const companyLinkClassName =
  "text-gray-a12 underline decoration-gray-a8 [text-decoration-skip-ink:none] [text-decoration-thickness:10%] outline-none transition-[text-decoration-color] duration-200 ease-out focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-focus-ring";

const companyHoverClassName: Record<WorkAccent, string> = {
  red: "hover:decoration-red-a6",
  purple: "hover:decoration-purple-a6",
  blue: "hover:decoration-blue-a6",
  yellow: "hover:decoration-yellow-a6",
};

export type WorkRowProps = {
  icon: WorkIconName;
  role: string;
  company: WorkCompany;
  via?: WorkCompany;
  dates: string;
  description: string;
  media?: WorkMediaItem[];
  viewProject?: boolean;
  assetCount?: number;
  className?: string;
};

export function WorkRow({
  icon,
  role,
  company,
  via,
  dates,
  description,
  media = [],
  viewProject = false,
  assetCount,
  className,
}: WorkRowProps) {
  const heading = `${role} at ${company.name}${via ? ` via ${via.name}` : ""}`;
  const visibleMedia = media.slice(0, assetCount);
  const params = useDialKit(
    "Work Media",
    {
      layout: {
        type: "select",
        options: [...WORK_MEDIA_LAYOUT_OPTIONS],
        default: "stack",
      },
    },
    {
      id: "work-media-layout",
      persist: true,
    },
  );
  const layout = workMediaLayoutFromDial(params.layout);

  return (
    <article className={cn("flex w-full flex-col gap-1.5", className)}>
      <div className="flex w-full items-center gap-2">
        <WorkRowIcon name={icon} />
        <h2 className="m-0 min-w-0 text-sm font-normal leading-5 text-gray-a12">
          {role}{" "}
          <span className="text-gray-a11">at</span>{" "}
          <CompanyLink company={company} />
          {via ? (
            <>
              {" "}
              <span className="text-gray-a11">via</span>{" "}
              <CompanyLink company={via} />
            </>
          ) : null}
        </h2>
        <p className="m-0 ml-auto shrink-0 text-sm leading-5 text-gray-a10">
          {dates}
        </p>
      </div>
      <p className="m-0 w-full text-pretty text-sm leading-5 text-gray-a11">
        {description}
      </p>
      <WorkMediaCarousel
        heading={heading}
        items={visibleMedia}
        layout={layout}
        showViewProject={viewProject}
      />
    </article>
  );
}

function CompanyLink({ company }: { company: WorkCompany }) {
  return (
    <a
      href={company.href}
      target="_blank"
      rel="noopener noreferrer"
      className={cn(companyLinkClassName, companyHoverClassName[company.accent])}
    >
      {company.name}
    </a>
  );
}

function WorkRowIcon({ name }: { name: WorkIconName }) {
  const src = FIGMA_ICON_ASSETS[name];

  return (
    <span aria-hidden className="relative size-4 shrink-0 overflow-hidden">
      {src ? (
        <Image
          src={src}
          alt=""
          fill
          sizes="16px"
          className="object-cover"
        />
      ) : (
        ICONS[name]
      )}
    </span>
  );
}

